/**
 * SDK Vite preset for runtime-delivered plugin clients (design D9/D10/D17, tasks 7.2, 7.3).
 *
 * Builds a plugin's `clientBundle` for the host's import map:
 *  - an ES **entry module** (`<outDir>/index.js`: claim functions + eager components) plus one stable-named lazy
 *    chunk per claim `module` (`<outDir>/<name>.js`, shared code goes to `<outDir>/chunks/`);
 *  - EVERY import-map specifier external (React, the runtime, `<EmbeddedApp>`, app-kit/react, wouter — the host
 *    serves one instance of each, so contexts and singletons are shared);
 *  - a utilities-only Tailwind v4 stylesheet (`<outDir>/client.css`: no preflight, no `:root` theme redeclare;
 *    theming goes through the host's CSS custom properties);
 *  - a build-FAILING guard when the bundle would contain React or a client-utils singleton module.
 *
 * `dashboardStandaloneViteConfig` builds the SAME source as a standalone SPA (its own React — the standalone half
 * of "one app, two builds"). Pure config builders: `vite` and `@tailwindcss/vite` load lazily, only on build.
 *
 * See change: decouple-plugins-from-core (tasks 7.2, 7.3; specs plugin-runtime-client-loading).
 */
import fs from "node:fs";
import path from "node:path";
import { HOST_IMPORT_MAP_SPECIFIERS } from "@blackbelt-technology/pi-dashboard-shared/dashboard-plugin/host-import-map.js";
import type { InlineConfig, Plugin } from "vite";

/** Every import-map specifier — external in a runtime bundle. Same list the server's import map serves. */
export const CLIENT_PRESET_EXTERNALS: readonly string[] = HOST_IMPORT_MAP_SPECIFIERS;

const REACT_SPECIFIERS = new Set(["react", "react/jsx-runtime", "react-dom", "react-dom/client"]);

export interface ClientPresetOptions {
  /** Plugin package dir (vite `root`). Default `process.cwd()`. */
  root?: string;
  /** Entry module source, relative to `root` (e.g. `src/client/index.tsx`). Becomes `<outDir>/index.js`. */
  entry: string;
  /** Lazy claim `module` chunks: output name → source path. Each becomes `<outDir>/<name>.js`; name them in the manifest `module`. */
  lazyModules?: Readonly<Record<string, string>>;
  /** Output dir, relative to `root`. Default `dist/client`. It must be a DEDICATED client dir (never hold the server/bridge entry). */
  outDir?: string;
  /**
   * Utilities-only stylesheet `<outDir>/client.css`. `false` = none. `sources` = dirs Tailwind scans for class names
   * (default: the entry's dir and every lazy module's dir).
   */
  styles?: false | { sources?: readonly string[] };
  /**
   * TEST ONLY. Import-map specifiers to BUNDLE instead of leaving external (failure-variant fixtures). Listing a React
   * specifier also turns the React half of the singleton guard off. Never set this in a real plugin: two Reacts =
   * broken hooks and contexts.
   */
  unsafeBundleSpecifiers?: readonly string[];
  /** Extra Vite config, deep-merged over the preset's (e.g. `resolve.alias`). */
  vite?: InlineConfig;
}

// ── CSS template ──────────────────────────────────────────────────────────

/** The utilities-only Tailwind v4 entry (D17): theme as reference (no `:root` redeclare), utilities, NO preflight. */
export function clientStylesTemplate(sources: readonly string[]): string {
  const sourceLines = sources.map((dir) => `@source ${JSON.stringify(dir.replace(/\\/g, "/"))};`);
  return [
    "/* Generated by the dashboard client preset: utilities only, host theme variables by reference. */",
    '@import "tailwindcss/theme.css" theme(reference);',
    '@import "tailwindcss/utilities.css";',
    ...sourceLines,
    "",
  ].join("\n");
}

// ── Singleton guard ───────────────────────────────────────────────────────

interface GuardRule {
  pattern: RegExp;
  /** One-line remedy. */
  remedy: string;
  react: boolean;
}

const GUARD_RULES: readonly GuardRule[] = [
  {
    pattern: /\/node_modules\/(?:react|react-dom|scheduler)\//,
    remedy:
      'import React from the host through the import map — use the bare specifiers "react", "react/jsx-runtime", "react-dom" or "react-dom/client" (never a deep path like react/jsx-dev-runtime or react-dom/server); the host serves ONE React',
    react: true,
  },
  {
    pattern: /\/client-utils\/(?:src|dist)\/(?:useMobile|LayerPortal|escape-stack|ActionListMenuContext)\.[cm]?[jt]sx?$/,
    remedy:
      "this client-utils module owns a context or singleton the host also holds — a bundled copy is a second, disconnected instance. Use the host's primitives (useUiPrimitive from the runtime) instead of importing it",
    react: false,
  },
];

const normalize = (id: string): string => id.replace(/^\0/, "").replace(/\?.*$/, "").replace(/\\/g, "/");

/** Rule hits for one module id (`allowReact` skips the React rule). */
function moduleViolations(id: string, allowReact: boolean): string[] {
  const norm = normalize(id);
  const short = norm.replace(/^.*?\/(node_modules\/|packages\/)/, "$1");
  return GUARD_RULES.filter((rule) => !(rule.react && allowReact) && rule.pattern.test(norm)).map((rule) => `  - ${short}\n    → ${rule.remedy}`);
}

/** Every distinct violation across the emitted chunks. */
function bundleViolations(bundle: Record<string, { type: string; modules?: Record<string, unknown> }>, allowReact: boolean): string[] {
  const hits = Object.values(bundle).flatMap((chunk) => (chunk.type === "chunk" ? Object.keys(chunk.modules ?? {}) : [])).flatMap((id) => moduleViolations(id, allowReact));
  return [...new Set(hits)];
}

/** Rollup plugin: fail `generateBundle` when a chunk contains React or a client-utils singleton module. */
export function dashboardSingletonGuard(opts: { allowReact?: boolean } = {}): Plugin {
  return {
    name: "pi-dashboard-singleton-guard",
    generateBundle(_output, bundle) {
      const violations = bundleViolations(bundle, opts.allowReact === true);
      if (violations.length > 0) {
        this.error(
          `[pi-dashboard preset] the plugin bundle must not include modules the host already provides:\n${violations.join("\n")}\n` +
            `Import-map specifiers (external, one shared instance): ${CLIENT_PRESET_EXTERNALS.join(", ")}`,
        );
      }
    },
  };
}

// ── Config builders ───────────────────────────────────────────────────────

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Small deep merge (plain objects merge, arrays concat, scalars override) — keeps `vite` out of the pure builders. */
function deepMerge<T extends Record<string, unknown>>(base: T, over: Record<string, unknown>): T {
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(over)) {
    const cur = out[k];
    if (isPlainObject(cur) && isPlainObject(v)) out[k] = deepMerge(cur, v);
    else if (Array.isArray(cur) && Array.isArray(v)) out[k] = [...cur, ...v];
    else out[k] = v;
  }
  return out as T;
}

async function tailwindPlugin(): Promise<Plugin[]> {
  const mod = (await import("@tailwindcss/vite")) as unknown as { default: () => Plugin | Plugin[] };
  const made = mod.default();
  return Array.isArray(made) ? made : [made];
}

/** Writes the generated stylesheet under `<root>/node_modules/.cache` (git-ignored; resolves `tailwindcss` by walking up). */
function writeStylesheet(root: string, sources: readonly string[]): string {
  const dir = path.join(root, "node_modules", ".cache", "pi-dashboard-client-preset");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, "client.css");
  const content = clientStylesTemplate(sources);
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) fs.writeFileSync(file, content);
  return file;
}

/** Prepends the stylesheet import to the entry so Vite extracts it as `client.css`. */
function stylesheetInjector(entryAbs: string, cssFile: string): Plugin {
  return {
    name: "pi-dashboard-client-styles",
    enforce: "pre",
    transform(code, id) {
      if (path.resolve(normalize(id)) !== entryAbs) return null;
      return { code: `import ${JSON.stringify(cssFile.replace(/\\/g, "/"))};\n${code}`, map: null };
    },
  };
}

/** Plugins for the entry build: stylesheet (unless `styles:false`) then the singleton guard. */
async function clientPlugins(opts: ClientPresetOptions, root: string, entryAbs: string, lazy: Record<string, string>, allowReact: boolean): Promise<Plugin[]> {
  const plugins: Plugin[] = [];
  if (opts.styles !== false) {
    const dirs = [entryAbs, ...Object.values(lazy)].map((f) => path.dirname(f));
    const sources = opts.styles?.sources?.map((s) => path.resolve(root, s)) ?? [...new Set(dirs)];
    plugins.push(stylesheetInjector(entryAbs, writeStylesheet(root, sources)), ...(await tailwindPlugin()));
  }
  plugins.push(dashboardSingletonGuard({ allowReact }));
  return plugins;
}

/** Deep-merge the caller's extra Vite config (if any) over `base`. */
function withOverrides(base: InlineConfig, extra: InlineConfig | undefined): InlineConfig {
  return extra ? (deepMerge(base as Record<string, unknown>, extra as Record<string, unknown>) as InlineConfig) : base;
}

/** Vite config for the runtime-delivered `clientBundle` build. */
export async function dashboardClientViteConfig(opts: ClientPresetOptions): Promise<InlineConfig> {
  const root = path.resolve(opts.root ?? process.cwd());
  const entryAbs = path.resolve(root, opts.entry);
  const lazy = Object.fromEntries(Object.entries(opts.lazyModules ?? {}).map(([name, src]) => [name, path.resolve(root, src)]));
  const bundled = new Set(opts.unsafeBundleSpecifiers ?? []);
  const externals = CLIENT_PRESET_EXTERNALS.filter((s) => !bundled.has(s));
  const allowReact = [...bundled].some((s) => REACT_SPECIFIERS.has(s));

  return withOverrides(
    {
      root,
      configFile: false,
      mode: "production",
      logLevel: "warn",
      plugins: await clientPlugins(opts, root, entryAbs, lazy, allowReact),
      // Automatic JSX emits `react/jsx-runtime` imports (an import-map external). `jsxDev: false` is explicit: Vite
      // derives it from NODE_ENV, and the dev runtime (`react/jsx-dev-runtime`) is NOT in the import map.
      esbuild: { jsx: "automatic", jsxDev: false },
      define: { "process.env.NODE_ENV": JSON.stringify("production") },
      build: {
        outDir: path.resolve(root, opts.outDir ?? "dist/client"),
        emptyOutDir: true,
        target: "es2022",
        sourcemap: false,
        lib: {
          entry: { index: entryAbs, ...lazy },
          formats: ["es"],
          fileName: (_format: string, name: string) => `${name}.js`,
          cssFileName: "client",
        },
        rollupOptions: {
          external: (id: string) => externals.includes(id),
          output: { chunkFileNames: "chunks/[name]-[hash].js" },
        },
      },
    },
    opts.vite,
  );
}

/** Build the runtime `clientBundle` (entry + lazy chunks + `client.css`) with {@link dashboardClientViteConfig}. */
export async function buildDashboardClient(opts: ClientPresetOptions): Promise<void> {
  const { build } = await import("vite");
  await build(await dashboardClientViteConfig(opts));
}

export interface StandalonePresetOptions {
  /** App dir holding `index.html`. Default `process.cwd()`. */
  root?: string;
  /** Output dir, relative to `root`. Default `dist/standalone`. */
  outDir?: string;
  /** Extra Vite config, deep-merged over the preset's. */
  vite?: InlineConfig;
}

/** Vite config for the standalone SPA half of the same app: its own React, full Tailwind from the app's own CSS. */
export async function dashboardStandaloneViteConfig(opts: StandalonePresetOptions = {}): Promise<InlineConfig> {
  const root = path.resolve(opts.root ?? process.cwd());
  return withOverrides(
    {
      root,
      configFile: false,
      base: "./",
      plugins: await tailwindPlugin(),
      esbuild: { jsx: "automatic" },
      build: { outDir: path.resolve(root, opts.outDir ?? "dist/standalone"), emptyOutDir: true },
    },
    opts.vite,
  );
}

/** Build the standalone SPA with {@link dashboardStandaloneViteConfig}. */
export async function buildDashboardStandalone(opts: StandalonePresetOptions = {}): Promise<void> {
  const { build } = await import("vite");
  await build(await dashboardStandaloneViteConfig(opts));
}
