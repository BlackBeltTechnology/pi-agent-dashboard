const TIER_BY_ROUTE = new Map<string, Tier>(
  ROUTE_TIERS.map((e) => [`${e.method} ${e.path}`, e.tier]),
);

/**
 * Required tier for a REST route pattern. Unlisted → `operate` (fail closed).
 */
export function routeTier(method: string, path: string): Tier {
  return TIER_BY_ROUTE.get(`${method.toUpperCase()} ${path}`) ?? "operate";
}

/** Whether the map has an explicit entry for a route (completeness check). */
export function hasRouteTier(method: string, path: string): boolean {
  return TIER_BY_ROUTE.has(`${method.toUpperCase()} ${path}`);
}
