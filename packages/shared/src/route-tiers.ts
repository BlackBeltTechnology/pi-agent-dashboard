/**
 * Route → tier map (see change: expand-mcp-tiered-surface, design D1b/D7).
 *
 * ONE source of truth for the tier a REST route requires. Two consumers read
 * it: the server's REST tier gate (`auth/route-tier-gate.ts`) and the MCP
 * manifest's `rest` rows (their tool tier is the route's tier, or higher for
 * the sanctioned lifecycle actions). One definition, so the two surfaces cannot
 * disagree.
 *
 * Fail-closed: an UNLISTED route resolves to `operate`, the strongest tier.
 * The completeness test fails an /api route missing from this list, so an
 * untriaged route is a build failure rather than a silent `operate`.
 *
 * Scope: `/api/*` only. `/mcp`, `/auth/*` and `/v1/*` have their own
 * admission and are outside this map.
 */
